// Generates CONTENT_GUIDE.md — a single self-contained briefing you can upload
// to Claude chat to help author new archetypes / cats / questions in the exact
// format the build pipeline expects. Regenerate after adding content:
//
//   npm run guide
//
// The current-inventory sections are read live from data/*.json so the guide is
// always accurate; the prose/format sections are maintained here.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(resolve(ROOT, "data", f), "utf8"));

const archetypes = read("archetypes.json").archetypes;
const cats = read("cats.json").cats;
const questions = read("questions.json").questions;

const nameById = new Map(archetypes.map((a) => [a.id, a.name]));
const tagName = (id) => (nameById.get(id) || id).replace(/^The /, "");

// ---- dynamic blocks (built with plain strings so backticks stay literal) ----

const archetypeBlock = archetypes
  .map(
    (a, i) =>
      (i + 1) +
      ". **" +
      a.name +
      "** — `" +
      a.id +
      "`\n   _Tagline:_ " +
      a.tagline +
      "\n   " +
      a.description
  )
  .join("\n\n");

const rarityCount = cats.reduce((m, c) => ((m[c.rarity] = (m[c.rarity] || 0) + 1), m), {});
const wild = cats.filter((c) => c.origin === "wild").length;

const rosterBlock = archetypes
  .map((a) => {
    const list = cats
      .filter((c) => c.archetype === a.id)
      .map((c) => "  - " + c.name + " — " + c.rarity + ", " + c.origin)
      .join("\n");
    return "**" + a.name + "** (`" + a.id + "`)\n" + list;
  })
  .join("\n\n");

const questionBlock = questions
  .map((q) => "- **Q" + q.id.replace(/^q/, "") + ". " + q.title + "** — " + q.setup)
  .join("\n");

// Filled examples pulled live from the data, shown in SOURCE markdown format.
const exA = archetypes[0];
const exArchetype =
  "## " + exA.name + "\n- **ID:** `" + exA.id + "`\n- **Tagline:** " + exA.tagline + "\n\n" + exA.description + "\n\n---";

const exC = cats[0];
const exCat =
  "## " + nameById.get(exC.archetype) + "\n\n**" + exC.name + "** *(" + exC.rarity + ")*\n" + exC.blurb + "\n*Trivia: " + exC.trivia + "*";

const exQ = questions[0];
const exQuestion =
  "### Q" + exQ.id.replace(/^q/, "") + ". " + exQ.title + ".\n*" + exQ.setup + "*\n\n" +
  exQ.answers
    .map((ans, i) => "- **" + String.fromCharCode(65 + i) + ".** " + ans.text + "\n  → " + ans.tags.map(tagName).join(", "))
    .join("\n");

const stats =
  "- **" + archetypes.length + " archetypes**\n" +
  "- **" + cats.length + " cats** — by rarity: " +
  Object.entries(rarityCount).map(([k, v]) => v + " " + k).join(", ") +
  "; by origin: " + (cats.length - wild) + " domestic / " + wild + " wild\n" +
  "- **" + questions.length + " questions** (the quiz pulls 10 at random)";

// ---- the document (template literal; backticks escaped as \`) --------------

const doc = `# My Inner Cat — Content Guide & Current State

> Upload this single file to Claude chat to help write new content. It explains
> what the app is, the exact formats new content must follow, the rules, and a
> full snapshot of everything that already exists (so you don't duplicate or
> unbalance it). Auto-generated by \`npm run guide\` — regenerate after adding content.

---

## 1. What the app is

**My Inner Cat** (myinnercat.com) is a wholesome watercolor cat personality quiz.
You answer **10 of the ${questions.length} questions** (pulled at random), get matched to one of
**${archetypes.length} personality archetypes**, and are then dealt **one of ${cats.length} cats** from that
archetype — revealed as a **collectible card** with a rarity tier you can share,
download, and collect. Cats range from cozy housecats to rare wild species, each
an original watercolor painting.

- **Audience:** general, ages ~10–70+. Kids enjoy the collecting + cute cats;
  adults enjoy the writing + the (true) trivia.
- **Tone:** warm, gentle, encouraging, unhurried. Never snarky, clinical, or salesy.

## 2. The voice (match this exactly)

- **Archetype description** — second person, speaks *to* the reader about who they
  are. Affirming and specific, ~3–5 sentences. E.g. "You're the friend people text
  when something hard happens. You don't panic, you don't perform…"
- **Archetype tagline** — one punchy line, sentence fragment ok. E.g. "Would rather
  be tired than bored."
- **Cat blurb** — third person, warm, ~2–4 sentences about *the cat* (its
  temperament + a charming detail) and why it fits the archetype's vibe.
- **Cat trivia** — factual and genuinely surprising or "earned." 1–2 sentences.
  Real facts only.

## 3. How content becomes the app

There are **three source markdown files**. A build script parses them into JSON,
validates everything, and optimizes the images — then the whole app (results,
gallery, share cards, sitemap, the "${cats.length} cats / ${archetypes.length} archetypes" copy) scales
automatically. You only ever edit the markdown + add art.

| Source file | Produces |
|---|---|
| \`archetype_data.md\` | the ${archetypes.length} archetypes |
| \`cat_profiles_and_trivia.md\` | the ${cats.length} cats (a cat's archetype = its \`##\` section) |
| \`cat_quiz_scoring_tags.md\` | the ${questions.length} questions + scoring tags |

## 4. Exact formats (new content must match these)

### A new archetype — in \`archetype_data.md\`
\`\`\`md
## The Example Archetype
- **ID:** \`example_archetype\`
- **Tagline:** A short, punchy one-liner.

The description paragraph, second person, ~3–5 affirming sentences.

---
\`\`\`
Real example:
\`\`\`md
${exArchetype}
\`\`\`

### A new cat — in \`cat_profiles_and_trivia.md\`
Cats live under a \`## Archetype Name\` section header — **that header is what
assigns the cat to its archetype.** Format per cat:
\`\`\`md
**Cat Name** *(rarity)*
The blurb paragraph.
*Trivia: The trivia sentence.*
\`\`\`
Real example (header + one cat):
\`\`\`md
${exCat}
\`\`\`

### A new question — in \`cat_quiz_scoring_tags.md\`
\`\`\`md
### Q99. The question title.
*The scenario setup sentence.*

- **A.** First answer text.
  → Archetype Name, Archetype Name, Archetype Name
- **B.** Second answer text.
  → Archetype Name, Archetype Name
\`\`\`
Real example:
\`\`\`md
${exQuestion}
\`\`\`
(Archetype names in the \`→\` line use the display name; a leading "The" is optional —
the parser matches case-insensitively.)

## 5. Rules & conventions

- **Rarity tiers:** \`common\` | \`uncommon\` | \`rare\` | \`legendary\`. At reveal, rarer =
  less likely (weights common 40 / uncommon 30 / rare 20 / legendary 10). Make the
  most striking / elusive / wild cats the rarer tiers; everyday housecats are common.
- **Cat IDs** are derived automatically: lowercase, spaces→\`_\`, drop apostrophes &
  possessive "'s", strip accents. (Pallas's Cat → \`pallas_cat\`, Guiña → \`guina\`.)
- **Images:** every cat needs a watercolor painting in \`images/\`, named from the cat
  name: lowercase, accents stripped, apostrophes removed, spaces/hyphens → \`-\`, \`.png\`
  (e.g. "Norwegian Forest Cat" → \`norwegian-forest-cat.png\`). The build optimizes it
  to WebP automatically. **No image = the cat can't ship.**
- **Wild species:** if a new cat is a wild species (not a domestic breed), it must be
  added to the \`WILD_SPECIES\` set in \`scripts/build-data.mjs\` so it's labeled correctly.
- **Question tags:** each answer should tag **3–5 archetypes** (a few 2-tag answers
  exist intentionally). Tags are how matching works — every answer's tags each add a
  point; highest total wins.
- **CRITICAL — keep archetypes matchable & balanced:** a new archetype is only ever
  reachable if it's **tagged across several answers** in the questions. Add a new
  archetype and you MUST sprinkle its tag through the question pool, or no one can get
  it. Likewise, give each archetype a healthy spread of cats across rarities.
- Some archetypes are broad and naturally match more (Old Soul, Quiet Mystic); some
  are specific and should match rarely (Night Owl, Quirky Individualist). Don't force
  a perfectly flat distribution.

## 6. Current inventory (the snapshot)

${stats}

### The ${archetypes.length} archetypes
${archetypeBlock}

### The ${cats.length} cats (grouped by archetype)
${rosterBlock}

### The ${questions.length} questions
${questionBlock}

## 7. Expanding — balance checklist

When adding content, keep these in mind:
- **New archetype** → write its entry, then **tag it into ~6–10 answers** across the
  question pool, and give it **4–5 cats** spread across rarities (incl. ≥1 common so
  it's reachable, and ideally a legendary for the chase).
- **New cat** → pick the archetype whose vibe it fits; choose a rarity that keeps that
  archetype's spread sensible; write blurb + trivia in voice; add the painting.
- **New question** → a fresh everyday scenario (don't repeat existing themes — see the
  list above); 3–4 answers; each answer tags 3–5 archetypes that the choice implies.
- After editing: \`npm run data\` (validates + optimizes), then \`npm run build\`,
  commit, push. Re-run \`npm run guide\` to refresh this file.

## 8. How to ask Claude chat for content

Paste this guide, then ask for what you want and request paste-ready output, e.g.:

> "Using the formats and voice in this guide, write **3 new archetypes** (with ids,
> taglines, descriptions), **4 cats each** (names, rarities, blurbs, trivia, and the
> image filename I'll need), and **6 new questions** that tag toward them. Avoid
> duplicating any existing archetype, cat, or question theme. Output each in the exact
> markdown format for its source file, ready to paste."

Ask it to also list the **image filenames** you'll need to create for any new cats.
`;

writeFileSync(resolve(ROOT, "CONTENT_GUIDE.md"), doc);
console.log(
  "Wrote CONTENT_GUIDE.md — " +
    archetypes.length +
    " archetypes, " +
    cats.length +
    " cats, " +
    questions.length +
    " questions."
);
